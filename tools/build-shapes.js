'use strict';

var fs = require('fs');
var os = require('os');
var path = require('path');
var execFileSync = require('child_process').execFileSync;

var src = process.argv[2];
if (!src || !fs.existsSync(src)) {
  console.error('Usage: node tools/build-shapes.js <shapes folder>');
  process.exit(1);
}
var out = path.join(__dirname, '..', 'js', 'shape-library.js');

function round(n) {
  return Math.round(n * 100) / 100;
}

/** Parse "matrix(a, b, c, d, e, f)"; anything else is treated as identity. */
function parseMatrix(t) {
  var m = t && /matrix\(([^)]*)\)/.exec(t);
  if (!m) return [1, 0, 0, 1, 0, 0];
  return m[1].split(/[\s,]+/).filter(Boolean).map(Number);
}

/** Parse pdftocairo path data (absolute M, L, C, Z) into point lists per command. */
function parsePath(d, m) {
  var tokens = d.match(/[MLCZmlcz]|-?[\d.]+(?:e-?\d+)?/g) || [];
  var cmds = [];
  var i = 0, cmd = null;
  function pt() {
    var x = Number(tokens[i++]), y = Number(tokens[i++]);
    return [m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5]];
  }
  while (i < tokens.length) {
    if (/[A-Za-z]/.test(tokens[i])) cmd = tokens[i++].toUpperCase();
    if (cmd === 'M' || cmd === 'L') cmds.push([cmd].concat(pt()));
    else if (cmd === 'C') cmds.push(['C'].concat(pt(), pt(), pt()));
    else if (cmd === 'Z') cmds.push(['Z']);
    else i++;
    if (cmd === 'Z') cmd = null;
  }
  return cmds;
}

function convert(pdf) {
  var tmp = path.join(os.tmpdir(), 'alchemy-shape-' + process.pid + '.svg');
  execFileSync('pdftocairo', ['-svg', pdf, tmp]);
  var svg = fs.readFileSync(tmp, 'utf8');
  fs.unlinkSync(tmp);

  var vb = /viewBox="([^"]+)"/.exec(svg);
  var page = vb ? vb[1].split(/\s+/).map(Number) : [0, 0, Infinity, Infinity];
  var pageW = page[2], pageH = page[3];
  var shapes = [];
  var re = /<path\b([^>]*)\/>/g, match;
  while ((match = re.exec(svg))) {
    var attrs = match[1];
    var d = /\sd="([^"]*)"/.exec(attrs);
    if (!d) continue;
    var cmds = parsePath(d[1], parseMatrix((/\stransform="([^"]*)"/.exec(attrs) || [])[1]));
    var xs = [], ys = [];
    cmds.forEach(function (c) {
      for (var k = 1; k < c.length; k += 2) { xs.push(c[k]); ys.push(c[k + 1]); }
    });
    if (!xs.length) continue;
    var minX = Math.min.apply(null, xs), minY = Math.min.apply(null, ys);
    var w = Math.max.apply(null, xs) - minX, h = Math.max.apply(null, ys) - minY;
    // Skip page-sized shapes (backgrounds, frames), like getPDFShapes
    if (w >= pageW || h >= pageH || w === 0 && h === 0) continue;
    var dOut = cmds.map(function (c) {
      var s = c[0];
      for (var k = 1; k < c.length; k += 2) s += ' ' + round(c[k] - minX) + ' ' + round(c[k + 1] - minY);
      return s;
    }).join(' ');
    shapes.push(dOut);
  }
  return shapes;
}

var groups = [];
var entries = fs.readdirSync(src, { withFileTypes: true }).sort(function (a, b) {
  return a.name.localeCompare(b.name);
});
var rootShapes = [];
entries.forEach(function (e) {
  var full = path.join(src, e.name);
  if (e.isDirectory() && e.name.charAt(0) !== '.') {
    var shapes = [];
    fs.readdirSync(full).sort().forEach(function (f) {
      if (/\.pdf$/i.test(f)) shapes = shapes.concat(convert(path.join(full, f)));
    });
    if (shapes.length) groups.push({ name: e.name, shapes: shapes });
  } else if (/\.pdf$/i.test(e.name)) {
    rootShapes = rootShapes.concat(convert(full));
  }
});
if (rootShapes.length) groups.unshift({ name: 'Shapes', shapes: rootShapes });

var body = '/*\n * Alchemy Web - js/shape-library.js\n' +
  ' * Generated by tools/build-shapes.js from the PDFs in Alchemy\'s `shapes` folder.\n' +
  ' * Do not edit by hand. Each shape is SVG path data moved to 0,0.\n' +
  ' * Part of Alchemy, GPLv3; see LICENSE.\n */\n' +
  'window.Alchemy = window.Alchemy || {};\n' +
  'window.Alchemy.shapeLibrary = ' + JSON.stringify(groups) + ';\n';
fs.writeFileSync(out, body);
groups.forEach(function (g) { console.log(g.name + ': ' + g.shapes.length + ' shapes'); });
console.log('Wrote ' + path.relative(process.cwd(), out) + ' (' + Math.round(body.length / 1024) + ' KB)');
